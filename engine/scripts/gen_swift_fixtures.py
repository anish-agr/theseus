"""Generate Swift parity fixtures from the Python reference engine.

    python engine/scripts/gen_swift_fixtures.py

Writes apps/navcore/Tests/NavCoreTests/*Parity.swift: batteries of
(input, expected) pairs computed by the REFERENCE implementation, so the
Swift port is tested against the exact numbers Python produces — the
port contract of docs/PORT.md, mechanized. Python's repr() emits the
shortest decimal that round-trips the IEEE double, and Swift parses
literals to the nearest double, so values survive the trip bit-exact.

Pure-arithmetic functions must match to the last bit (== in Swift);
libm-backed ones (trig, hypot) may differ by an ulp across C libraries,
so their cases carry a 1e-12 relative tolerance instead.
"""

